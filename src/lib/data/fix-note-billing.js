export function formatFixNoteCharge(billing) {
  if (!billing || !Number.isSafeInteger(billing.amountCents)) return "";
  return new Intl.NumberFormat("en-US", { style: "currency", currency: billing.currency }).format(billing.amountCents / 100);
}
